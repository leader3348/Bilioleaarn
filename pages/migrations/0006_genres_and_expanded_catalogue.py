def seed_expanded_catalogue(apps, schema_editor):
    Book = apps.get_model("pages", "Book")
    for title, author, year, category in BOOKS:
        Book.objects.get_or_create(
            title=title,
            author=author,
            defaults={
                "published_year": year,
                "category": category,
                "series": "",
                "volume": 1,
            },
        )


